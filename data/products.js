/**
 * Returns all active products.
 */
export function getAllProducts() {
  return products.filter((p) => p.active);
}

/**
 * Returns products marked as featured for the homepage.
 */
export function getFeaturedProducts() {
  return products.filter((p) => p.active && p.featured);
}

/**
 * Finds a single product by slug.
 */
export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug);
}

/**
 * Filters products by category id or returns all if empty or 'all'.
 */
export function getProductsByCategory(categoryId) {
  if (!categoryId || categoryId === "all") return getAllProducts();
  return products.filter(
    (p) => p.active && p.categoryId.toLowerCase() === categoryId.toLowerCase()
  );
}
